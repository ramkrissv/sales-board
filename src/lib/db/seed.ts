// ─── Main seed function ─────────────────────────────────────────────────────

export async function seed() {
  const MONGODB_URI = process.env.MONGODB_URI || 'mongodb://localhost:27017/galent';
  console.log(`[seed] Connecting to MongoDB at ${MONGODB_URI}...`);
  await mongoose.connect(MONGODB_URI);
  console.log('[seed] Connected.');

  // Check if data already exists
  const existingCount = await Opportunity.countDocuments();
  if (existingCount > 0 && process.env.FORCE_RESEED !== 'true') {
    console.log(`[seed] Database already has ${existingCount} opportunities — skipping seed.`);
    await mongoose.disconnect();
    return;
  }

  if (process.env.FORCE_RESEED === 'true') {
    console.log('[seed] FORCE_RESEED=true — clearing and reseeding...');
    await Opportunity.deleteMany({});
    await Stakeholder.deleteMany({});
    await Task.deleteMany({});
    await ServiceLine.deleteMany({});
    await Product.deleteMany({});
    await User.deleteMany({});
    console.log('[seed] Cleared all existing data.');
  } else {
    console.log('[seed] Empty database detected — seeding Galent pipeline data...');
  }

  // 1. Seed opportunities
  console.log('[seed] Inserting opportunities...');
  await Opportunity.insertMany(oppData);
  console.log(`[seed] ${oppData.length} opportunities inserted.`);

  // 2. Seed stakeholders
  console.log('[seed] Inserting stakeholders...');
  await Stakeholder.insertMany(stakeholderData);
  console.log(`[seed] ${stakeholderData.length} stakeholders inserted.`);

  // 3. Seed tasks
  console.log('[seed] Inserting tasks...');
  await Task.insertMany(taskData);
  console.log(`[seed] ${taskData.length} tasks inserted.`);

  // 4. Seed service lines
  console.log('[seed] Inserting service lines...');
  const serviceLineData = [
    {
      name: 'IT Services',
      code: 'ITS',
      color: '#5B4FE9',
      isActive: true,
      pipelineStages: ['Discovery', 'Qualification', 'Solutioning', 'Proposal', 'Negotiation', 'Won', 'Lost', 'On Hold'],
    },
    {
      name: 'Staffing',
      code: 'STF',
      color: '#00dc82',
      isActive: true,
      pipelineStages: ['Requirement', 'Sourcing', 'Submission', 'Interview', 'Offer', 'Placement', 'Lost'],
    },
  ];
  await ServiceLine.insertMany(serviceLineData);
  console.log(`[seed] ${serviceLineData.length} service lines inserted.`);

  // 5. Seed products
  console.log('[seed] Inserting products...');
  const productNames = [
    'AI Platform',
    'QA CoE',
    'DevSecOps',
    'Cloud Migration',
    'Data Analytics',
    'Contact Center AI',
  ];
  const productData = productNames.map((name) => ({ name, isActive: true }));
  await Product.insertMany(productData);
  console.log(`[seed] ${productData.length} products inserted.`);

  // 6. Seed default admin user
  console.log('[seed] Inserting default admin user...');
  await User.create({
    email: 'admin@galent.com',
    firstName: 'Admin',
    lastName: 'User',
    role: 'admin',
  });
  console.log('[seed] Admin user created (admin@galent.com).');

  // 7. Seed engagement types
  const { seedEngagementTypes } = await import('./seed-engagement-types');
  await seedEngagementTypes();

  console.log('[seed] Seeding complete.');
  await mongoose.disconnect();
}
