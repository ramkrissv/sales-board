import mongoose from 'mongoose';
import { Opportunity } from './models/opportunity';

// ─── Mongoose models defined inline (Stakeholder, Task, ServiceLine, Product, User) ───

const StakeholderSchema = new mongoose.Schema(
  {
    opportunityId: { type: String, required: true },
    name: { type: String, required: true },
    title: { type: String },
    email: { type: String, default: null },
    phone: { type: String, default: null },
    linkedInUrl: { type: String, default: null },
    isPrimaryContact: { type: Boolean, default: false },
    isDecisionMaker: { type: Boolean, default: false },
    notes: { type: String, default: '' },
  },
  { timestamps: true }
);
const Stakeholder =
  mongoose.models.Stakeholder || mongoose.model('Stakeholder', StakeholderSchema);

const TaskSchema = new mongoose.Schema(
  {
    opportunityId: { type: String, required: true },
    name: { type: String, required: true },
    owner: { type: String, required: true },
    dueDate: { type: Date, required: true },
    status: { type: String, enum: ['pending', 'complete', 'overdue'], default: 'pending' },
    priority: { type: String, enum: ['Critical', 'High', 'Medium', 'Low'], default: 'Medium' },
    notes: { type: String, default: '' },
  },
  { timestamps: true }
);
const Task = mongoose.models.Task || mongoose.model('Task', TaskSchema);

const ServiceLineSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, unique: true },
    code: { type: String, required: true, unique: true },
    color: { type: String, default: '#5B4FE9' },
    isActive: { type: Boolean, default: true },
    pipelineStages: { type: [String], default: [] },
  },
  { timestamps: true }
);
const ServiceLine =
  mongoose.models.ServiceLine || mongoose.model('ServiceLine', ServiceLineSchema);

const ProductSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, unique: true },
    isActive: { type: Boolean, default: true },
  },
  { timestamps: true }
);
const Product = mongoose.models.Product || mongoose.model('Product', ProductSchema);

const UserSchema = new mongoose.Schema(
  {
    email: { type: String, required: true, unique: true },
    firstName: { type: String, required: true },
    lastName: { type: String, required: true },
    role: { type: String, enum: ['admin', 'user', 'viewer'], default: 'user' },
  },
  { timestamps: true }
);
const User = mongoose.models.User || mongoose.model('User', UserSchema);

